"""What each metric requires of a dataset, shared by the generator and runner.

Both scripts need the same facts and used to hold neither in common: the runner
knew which metrics need which column, the generator knew nothing at all and
synthesised whatever the service returned. A dataset generated blind and scored
afterwards is how you pay for generation *and* inference before finding out the
pairing was never scoreable -- the failure this module exists to move earlier.
Factored out for the same reason as ``_agent_loader``: the two must not drift.

**Every input contract here is quoted from Google's own reference:**

    https://docs.cloud.google.com/gemini-enterprise-agent-platform/models/rubric-metric-details

That page lists each managed rubric metric with its exact required inputs, and
it is the authority. Nothing in this module should be inferred from a metric's
name, from the SDK source, or from a secondary summary of any of them. Read the
page before adding an entry.

`verify_metrics.py` confirms the page against the running service, and is worth
keeping for the two things a document cannot tell you: which metrics do not run
in the installed release regardless of their contract, and which spec version
the service actually serves -- the SDK asks for `hallucination_v2` and gets
`hallucination_v1` back. Re-run it after an `agentplatform` upgrade.

Documentation and sweep agree completely as of 2026-09-03, so VERIFIED below is
authoritative enough to refuse on: a metric absent from it is refused, not
warned about. `canary()` in `local_agent_evaluation.py` remains the backstop for
a service that has changed since.

Three independent constraints decide whether a metric can score a row:

- **Usable at all.** Fifteen of the SDK's twenty-five metrics cannot score an
  agent dataset -- see VERIFIED and WHY_NOT below.
- **Columns.** ``final_response_match`` compares against a golden ``reference``;
  ``grounding`` needs a ``context``. Neither can be synthesised, so both are
  reachable only from a hand-written dataset.
- **Turn mode.** A single-turn metric rejects multi-turn agent data server-side
  with a 400, per case, after billing. ``tool_use_quality`` on a conversation
  plan is the pairing to watch, because the generator emits plans by default.
"""

from _agent_loader import fail


# The metrics that actually scored an agent dataset, by turn family.
#
# Generated by `verify_metrics.py` on 2026-09-03 against agentplatform 1.164.0,
# evals API in us-central1. Ten of the SDK's twenty-five metrics work here. The
# other fifteen are listed in WHY_NOT below with the service's own reason.
#
# Re-run the sweep after an SDK upgrade rather than trusting this. It is a
# snapshot of a server-side contract, and the SDK's own GROUNDEDNESS deprecation
# warning is evidence those contracts change between versions.
VERIFIED = {
    "multi": {
        "multi_turn_task_success",
        "multi_turn_tool_use_quality",
        "multi_turn_trajectory_quality",
    },
    "single": {
        "final_response_quality",
        "general_quality",
        "hallucination",
        "instruction_following",
        "safety",
        "text_quality",
        "tool_use_quality",
    },
}

ALL_VERIFIED = VERIFIED["multi"] | VERIFIED["single"]

# Why each of the rest cannot be used, and what to reach for instead. Three
# distinct kinds of failure, worth telling apart because only the first is
# recoverable:
#
#   missing input -- the documented contract names an input this capability
#                    never produces. A hand-written dataset can carry it.
#   wrong subject -- the metric evaluates a model in a chat, not an agent with
#                    a tool trace. No column fixes that.
#   legacy        -- not a managed rubric metric at all. The docs list these
#                    only under "Backward compatibility", as the older metric
#                    prompt templates, and in this release their judge returns
#                    prose where the service expects JSON ("Error parsing JSON
#                    ... Input: {**Rating: 5 ..."). Nothing to feed them.
WHY_NOT = {
    "final_response_match": (
        "is documented as requiring a golden 'reference'",
        "final_response_quality",
    ),
    "grounding": (
        "is documented as requiring a supplied 'context'",
        "hallucination, which grounds against the tool trace instead",
    ),
    "groundedness": (
        "is a legacy metric superseded by grounding, and needs a 'context'",
        "hallucination",
    ),
    # Documented input is "prompt with multi-turn conversations" plus response:
    # a chat transcript evaluated at the model level. The agent multi-turn
    # metrics take `agent_eval_data` instead, which is the distinction the
    # shared `multi_turn_` prefix hides.
    "multi_turn_general_quality": (
        "evaluates a chat transcript, not the agent_eval_data trace",
        "multi_turn_task_success",
    ),
    "multi_turn_text_quality": (
        "evaluates a chat transcript, not the agent_eval_data trace",
        "multi_turn_task_success",
    ),
    # Neither appears anywhere in the managed-metric reference. They exist in
    # the SDK enum and nowhere else, so there is no contract to satisfy.
    "multi_turn_chat_quality": (
        "is not a documented managed metric",
        "multi_turn_task_success",
    ),
    "multi_turn_safety": (
        "is not a documented managed metric",
        "safety, scored in a separate single-turn run",
    ),
    # Documented as not supporting auto-generated rubrics, so it requires a
    # `rubric_groups` input you author yourself. Called without them the
    # service answers HTTP 500 rather than naming the missing input.
    "final_response_reference_free": (
        "requires hand-authored rubric_groups; it cannot generate its own rubrics",
        "final_response_quality, which generates them",
    ),
    "coherence": ("is a legacy metric prompt template", "text_quality"),
    "fluency": ("is a legacy metric prompt template", "text_quality"),
    "verbosity": ("is a legacy metric prompt template", "final_response_quality"),
    "question_answering_quality": (
        "is a legacy metric prompt template",
        "final_response_quality",
    ),
    "summarization_quality": (
        "is a legacy metric prompt template",
        "final_response_quality",
    ),
    "gecko_text2image": ("scores images, not agents", None),
    "gecko_text2video": ("scores video, not agents", None),
}

# Columns a metric needs that inference does not produce, checked so a missing
# column fails before the billed call rather than as a 400 on every row after
# it. Only meaningful for a founder supplying their own dataset -- on the
# generation path these metrics are refused outright by VERIFIED.
#
# `hallucination` is deliberately absent. It was added here after a run was
# reported failing on a missing `reference`, and that was a misreading: its
# documented inputs are `response`, `developer_instruction`, `tool_declarations`
# and `intermediate_events`, and it grounds each claim against the tool calls in
# the trace. `final_response_match` is the metric that demands a `reference`, and
# in a mixed set its error is easily attributed to the wrong metric -- which is
# why the runner now prints errors per metric name.
NEEDS_COLUMN = {
    # Documented inputs.
    "grounding": "context",
    "final_response_match": "reference",
    # Legacy, undocumented, or chat-level metrics. The column names here are the
    # ones the service asks for in its 400, since there is no reference page to
    # quote for any of them.
    "groundedness": "context",
    "multi_turn_safety": "history",
    "multi_turn_chat_quality": "history",
    "multi_turn_general_quality": "conversation_history",
    "multi_turn_text_quality": "conversation_history",
}

# The SDK evaluates two different dataset shapes, and these scripts only ever
# produce one of them.
#
#   agent shape -- `agent_eval_data`, the trace `run_inference(agent=...)`
#                  records: model inputs, responses and tool calls. The three
#                  documented agent multi-turn metrics take this and nothing
#                  else.
#   chat shape  -- a transcript, documented as "prompt with multi-turn
#                  conversations" plus `response`. No tool calls, no trajectory.
#
# Four metrics in the SDK want a chat shape, and all four carry the
# `multi_turn_` prefix that makes them look like the agent ones, so they pass
# every structural check and fail per case after billing. The reference page is
# what separates them: the agent metrics list `agent_eval_data` as their input,
# the chat ones list a prompt and a response. Two ask for `history` in their
# error and two for `conversation_history`; the distinction does not matter
# here, because `run_inference` writes neither.
#
# There is no conversion. A generated scenario has no transcript to become a
# history, so these are out of scope for this capability rather than merely
# missing a column.
CHAT_SHAPE = {
    "multi_turn_safety",
    "multi_turn_chat_quality",
    "multi_turn_general_quality",
    "multi_turn_text_quality",
}

# A metric is multi-turn if and only if its name says so. Everything else
# rejects multi-turn agent data, per case, with a 400 after billing.
#
# This was first written the other way round -- an allowlist of the metrics
# observed to be single-turn, with anything unlisted assumed to score either
# way. That fails open, and it let `final_response_quality` through both the
# generator and the runner into a paid run that could not be scored: the name
# suggests it inspects the last turn of anything, and it does not. There is no
# "scores either way" category to be permissive about, and no local source of
# truth to consult -- the input contract lives in the server-side metric spec
# (see the NEEDS_COLUMN note). So the rule is the naming convention, which is
# mechanical, needs no table, and cannot drift as metrics are added.
#
# A wrong guess in this direction costs a refusal the founder can override by
# splitting the run. In the other direction it costs a billed run that scores
# nothing.
def is_multi_turn(name):
    return name.startswith("multi_turn_")


# What to reach for when a single-turn metric is wanted but the dataset is
# multi-turn. Suggestions to put to the founder, never automatic swaps.
#
# Only three multi-turn metrics can score this dataset, so most of these
# collapse onto `multi_turn_task_success`. An earlier version of this table sent
# `general_quality` and `text_quality` to their same-named `multi_turn_`
# counterparts, which reads as the obvious mapping but does not hold: both of
# those score a chat transcript rather than an agent trace. Shared naming is not
# evidence of a shared input contract -- check the reference page.
CROSS_FAMILY = {
    "tool_use_quality": "multi_turn_tool_use_quality",
    "general_quality": "multi_turn_task_success",
    "text_quality": "multi_turn_task_success",
    "safety": "no multi-turn equivalent; score it in a separate single-turn run",
    # No multi_turn_final_response_* exists. Asking whether the goal was met
    # across the conversation is the nearest multi-turn question.
    "final_response_quality": "multi_turn_task_success",
    "final_response_match": "multi_turn_task_success",
    "hallucination": "multi_turn_task_success",
    "instruction_following": "multi_turn_task_success",
}

# What each metric is actually looking at, folded into the generation
# instruction so the scenarios exercise what is about to be measured. A
# generator told only "simulate realistic users" writes scenarios that never
# reach the tools, and then tool-use metrics score a conversation that had no
# tool calls in it. Unlisted metrics contribute their name alone.
MEASURES = {
    "multi_turn_task_success": "whether the user's goal is met across the whole conversation",
    "multi_turn_trajectory_quality": "sequencing, efficiency and recovery after an error",
    "multi_turn_tool_use_quality": "correctness of tool calls across the conversation",
    "tool_use_quality": "tool selection and parameter accuracy in a single exchange",
    "final_response_quality": "the final response together with the tool use behind it",
    "hallucination": "claims in the response that the tool results do not support",
    "instruction_following": "adherence to the instructions given in the prompt",
    "general_quality": "overall response quality in a single exchange",
    "text_quality": "fluency and coherence of the response",
    "safety": "policy compliance: PII, hate speech, dangerous content, harassment",
}


def normalise(names):
    """Split and clean a --metrics value into lowercase registry names."""
    if isinstance(names, str):
        names = names.split(",")
    return [n.strip().lower() for n in names if n.strip()]


# The spec version every metric is pinned to. Not cosmetic: without it, which
# spec scores the run is decided by the service, not by us.
#
# Unversioned metrics resolve through the SDK's METRIC_LATEST_SPEC_NAME, which
# asks for v2 or v3 for nine of the ten verified metrics -- and the service
# answers with v1 for all ten anyway. So today's behaviour depends on a silent
# server-side downgrade, and the day it stops, every run moves to a spec that
# the reference page does not document and this module has never tested.
#
# v1 is what the docs describe and what the sweep measured, so pinning makes the
# three agree. It is deliberately conservative: a newer spec is picked up when
# someone re-runs verify_metrics.py and moves this constant, not silently
# mid-demo.
PINNED_VERSION = "v1"


def _supported(spec_name):
    """Is this exact spec name one the installed SDK will send?"""
    try:
        from agentplatform._genai import _evals_constant

        return spec_name in _evals_constant.SUPPORTED_PREDEFINED_METRICS
    except Exception:  # pylint: disable=broad-exception-caught
        return False


def resolve_metrics(names, version=PINNED_VERSION):
    """Turn registry names into RubricMetric objects, or fail naming the set.

    Pinned to `version` where that version exists. Not every metric has a v1 --
    `final_response_match` starts at v2 -- and asking for a version that does
    not exist makes the SDK fall through to a GCS loader that does not resolve
    in this release, so an unavailable pin is left unversioned rather than
    forced.
    """
    from agentplatform import types

    available = {n.lower(): n for n in dir(types.RubricMetric) if n.isupper()}
    metrics = []
    for key in normalise(names):
        if key not in available:
            fail(f"unknown metric {key!r}. Available: {', '.join(sorted(available))}")
        metric = getattr(types.RubricMetric, available[key])
        if version and _supported(f"{key}_{version}"):
            metric = metric(version=version)
        metrics.append(metric)
    return metrics


def turn_mode(names):
    """Decide the row shape a set of metrics needs: 'multi' or 'single'.

    A set spanning both families has no shape that satisfies it, and says so:
    one file cannot be multi-turn for one metric and single-turn for another,
    because the `conversation_plan` column that creates multi-turn traces is a
    property of the file, not of the metric reading it.
    """
    names = normalise(names)
    multi = [n for n in names if is_multi_turn(n)]
    single = [n for n in names if not is_multi_turn(n)]
    if multi and single:
        swaps = "\n".join(
            f"    {n} -> {CROSS_FAMILY[n]}" for n in single if n in CROSS_FAMILY
        )
        fail(
            "the metrics span both turn families, and no single dataset scores both.\n"
            f"  multi-turn, needs a conversation_plan: {', '.join(multi)}\n"
            f"  single-turn, rejects one:              {', '.join(single)}\n"
            "\nA single-turn metric handed a multi-turn trace fails per case with "
            "HTTP 400,\nafter billing. Pick one family. Nearest multi-turn "
            "equivalents:\n" + (swaps or "    (none of these have one)")
            + "\n\nOr keep both by scoring twice: generate the multi-turn dataset, "
            "score the\nmulti-turn metrics on it, then copy it without the "
            "conversation_plan column\nand score the single-turn metrics on that. "
            "One generation, two scoring runs --\nso confirm the extra inference "
            "cost with the founder first."
        )
    return "multi" if multi else "single"


def require_verified(names, allow_unverified=False):
    """Refuse metrics the sweep did not see score, naming the substitute.

    This is the check that ends the guess-and-pay loop. Every other rule here
    infers from a name or a column; this one only says yes to a metric that has
    been observed returning a score, so a metric that reads as though it should
    work is refused until `verify_metrics.py` says otherwise.

    `allow_unverified` exists so the refusal is not a dead end -- a founder with
    a hand-written dataset carrying `reference` or `context` has a legitimate
    reason to run one of these, and the sweep only ever tested a generated one.
    It is not for getting past a refusal quickly.
    """
    blocked = [n for n in normalise(names) if n not in ALL_VERIFIED]
    if not blocked or allow_unverified:
        return
    lines = []
    for name in blocked:
        why, swap = WHY_NOT.get(name, ("was not seen to score anything", None))
        lines.append(f"  {name}: {why}." + (f" Use {swap} instead." if swap else ""))
    fail(
        "these metrics do not score an agent dataset on this SDK:\n"
        + "\n".join(lines)
        + "\n\nVerified and usable:\n"
        f"  multi-turn:  {', '.join(sorted(VERIFIED['multi']))}\n"
        f"  single-turn: {', '.join(sorted(VERIFIED['single']))}\n"
        "\nThat list is the output of verify_metrics.py, which scored one row "
        "with every\nmetric in the SDK. Put a substitution to the founder rather "
        "than applying it --\nthe recommendation is where they agreed what is "
        "being measured.\n\nIf you are supplying your own dataset with a "
        "'reference' or 'context' column,\n--allow-unverified skips this check; "
        "the sweep only tested a generated one."
    )


def missing_columns(columns, names):
    """Return [(metric, column)] for metrics whose required column is absent."""
    columns = set(columns)
    return [
        (name, NEEDS_COLUMN[name])
        for name in normalise(names)
        if name in NEEDS_COLUMN and NEEDS_COLUMN[name] not in columns
    ]


def describe(names):
    """One clause per metric for the generation instruction."""
    return [f"{n} ({MEASURES[n]})" if n in MEASURES else n for n in normalise(names)]
